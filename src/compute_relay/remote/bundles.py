"""Deterministic assembly of installed, reviewed stdlib-only remote programs.

Only the fixed component lists below are read. Neither a request, a manifest nor
a remote journal can select a source file or provide executable helper source.
Components declare normal Python imports. The linker resolves their explicit
first-party dependencies into one isolated program, without requiring a package
installation on the cluster or evaluating project code.
"""

import ast
import builtins
from dataclasses import dataclass
from functools import lru_cache
from graphlib import CycleError, TopologicalSorter
from importlib.resources import files
import symtable

from .protocol import JOB_PROTOCOL


DISCOVERY_PROTOCOL = "slurm-discovery/v1"
COMMON_COMPONENTS = ("prelude.py", "filesystem.py", "scheduler.py")
JOB_COMPONENTS = ("protocol.py", "jobs.py", "collection.py", "job_dispatch.py")
DISCOVERY_COMPONENTS = (
    "discovery_config.py", "probes.py", "module_catalog.py", "software.py", "discovery.py",
)
ENTRYPOINT = "entrypoint.py"
ENVIRONMENT_COMPONENTS = ("prelude.py", "probes.py", "environment_shell.py", "environment_probe.py", ENTRYPOINT)
_ALLOWED_COMPONENTS = frozenset((*COMMON_COMPONENTS, *JOB_COMPONENTS, *DISCOVERY_COMPONENTS, *ENVIRONMENT_COMPONENTS,
    ENTRYPOINT, "batch_status.py", "stream_entrypoint.py"))


def _component(name: str) -> str:
    if name not in _ALLOWED_COMPONENTS:
        raise ValueError("Unsupported fixed remote component")
    # Explicit newlines and no build paths, timestamps or platform metadata.
    return files("compute_relay.remote").joinpath(name).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n"


def component_names(kind: str) -> tuple[str, ...]:
    if kind == "jobs":
        return (*COMMON_COMPONENTS, *JOB_COMPONENTS, ENTRYPOINT)
    if kind == "discovery":
        return (*COMMON_COMPONENTS, *DISCOVERY_COMPONENTS, ENTRYPOINT)
    if kind == "environment":
        return ENVIRONMENT_COMPONENTS
    if kind in {"batch_status", "stream_jobs"}:
        return (*COMMON_COMPONENTS, *JOB_COMPONENTS, ENTRYPOINT, "batch_status.py",
            *(("stream_entrypoint.py",) if kind == "stream_jobs" else ()))
    raise ValueError("Unsupported fixed remote bundle")


@dataclass(frozen=True)
class LinkedComponent:
    source: str
    dependencies: tuple[tuple[str, tuple[str, ...]], ...]
    exports: frozenset[str]


def _global_references(scope):
    names = {symbol.get_name() for symbol in scope.get_symbols()
        if symbol.is_global() and symbol.is_referenced()}
    for child in scope.get_children():
        names.update(_global_references(child))
    return names


@lru_cache(maxsize=32)
def _link_component(name: str, source: str) -> LinkedComponent:
    """Remove only declared first-party imports; keep stdlib imports intact.

    The cache is bounded and keyed by actual source, so edits and test fixtures
    cannot reuse a stale dependency graph. Original source formatting is kept
    rather than regenerated by a Python-version-dependent AST formatter.
    """
    tree = ast.parse(source, filename=name)
    lines, dependencies = source.splitlines(keepends=True), []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ImportFrom) or not node.level:
            continue
        dependency = (node.module or "") + ".py"
        trailing = lines[node.end_lineno - 1][node.end_col_offset:].strip()
        if (node not in tree.body or node.level != 1 or dependency not in _ALLOWED_COMPONENTS
                or node.col_offset or trailing and not trailing.startswith("#")
                or any(alias.asname or alias.name == "*" for alias in node.names)):
            raise ValueError(f"Unsupported component import in {name}")
        members = tuple(alias.name for alias in node.names)
        dependencies.append((dependency, members))
        # Functions still share the bundle namespace, but every cross-component
        # name now has a checked import in its original, importable module.
        lines[node.lineno - 1:node.end_lineno] = [
            f"# Linked from .{node.module}: {', '.join(members)}\n",
            *["" for _ in range(node.end_lineno - node.lineno)],
        ]
    symbols = symtable.symtable(source, name, "exec")
    exports = frozenset(symbol.get_name() for symbol in symbols.get_symbols()
        if symbol.is_assigned() or symbol.is_imported() or symbol.is_namespace())
    if _global_references(symbols) - exports - set(dir(builtins)):
        raise ValueError(f"Unbound component dependency in {name}")
    return LinkedComponent("".join(lines), tuple(dependencies), exports)


def _assemble(names: tuple[str, ...], dispatch: str, protocol: str, *, entrypoint="main") -> str:
    if ENTRYPOINT not in names or len(names) != len(set(names)) or set(names) - _ALLOWED_COMPONENTS:
        raise ValueError("Unknown or duplicate remote component")
    components = {name: _link_component(name, _component(name)) for name in sorted(names)}
    for name, component in components.items():
        for dependency, members in component.dependencies:
            if dependency not in components or not set(members) <= components[dependency].exports:
                raise ValueError(f"Missing component dependency in {name}")
    graph = {name: tuple(sorted({dependency for dependency, _ in component.dependencies}))
        for name, component in components.items()}
    try:
        ordered = tuple(TopologicalSorter(graph).static_order())
    except CycleError:
        raise ValueError("Remote component dependencies contain a cycle") from None
    source = "# Compute Relay fixed remote bundle; generated deterministically.\n"
    source += "BUNDLE_PROTOCOL = " + repr(protocol) + "\n"
    for name in ordered:
        source += "\n# Component: " + name + "\n" + components[name].source
    if entrypoint not in {"main", "stream_main"}:
        raise ValueError("Unsupported fixed helper entrypoint")
    source += "\n" + dispatch + "\nif __name__ == '__main__':\n    " + entrypoint + "(execute)\n"
    return source


def bundle_source(kind: str) -> str:
    names = component_names(kind)
    if kind in {"batch_status", "stream_jobs"}:
        dispatch = ("def execute(config, request):\n"
                    "    if request.get('operation') == 'observe_many':\n"
                    "        return observe_many(config, request)\n"
                    "    return execute_jobs(config, request)\n") if kind == "stream_jobs" else (
                    "def execute(config, request):\n    return observe_many(config, request)\n")
        return _assemble(names, dispatch, JOB_PROTOCOL, entrypoint="stream_main" if kind == "stream_jobs" else "main")
    if kind == "environment":
        dispatch = ("def execute(config, request):\n"
                    "    if request.get('operation') != 'inspect_environment':\n"
                    "        raise ValueError('Unsupported fixed environment operation')\n"
                    "    return inspect_environment(config, request)\n")
        return _assemble(names, dispatch, "environment-inspection/v1")
    if kind == "jobs":
        dispatch = "def execute(config, request):\n    return execute_jobs(config, request)\n"
        return _assemble(names, dispatch, JOB_PROTOCOL)
    dispatch = ("def execute(config, request):\n"
                "    if request.get('operation') != 'discover':\n"
                "        raise ValueError('Unsupported fixed discovery operation')\n"
                "    return discover(config, request)\n")
    return _assemble(names, dispatch, DISCOVERY_PROTOCOL)


def local_inspection_source() -> str:
    """The same reviewed components together for in-process helper tests.

    This local facade is never selected or sent by a remote operation. It lets
    hostile-input tests patch a single namespace, identical to the one-shot
    interpreter, without importing any job, cluster or archived helper source.
    """
    names = (*COMMON_COMPONENTS, *JOB_COMPONENTS, *DISCOVERY_COMPONENTS, ENTRYPOINT)
    dispatch = ("def execute(config, request):\n"
                "    if request.get('operation') == 'discover':\n"
                "        return discover(config, request)\n"
                "    return execute_jobs(config, request)\n")
    return _assemble(names, dispatch, JOB_PROTOCOL)
